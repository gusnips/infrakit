#!/usr/bin/env bash
# Read-only probes. Inputs are validated and quoted by the CLI; no configuration is sourced.
# Validation chains fail when any read or validation fails.
# shellcheck disable=SC2015
set +x +v
set -o pipefail
export LC_ALL=C
export PATH="${PATH:-/usr/bin:/bin}:/usr/sbin:/sbin"
emit() { printf '%s\t%s\t%s\n' "$1" "$2" "${3:-}"; }
has() {
    local id=$1 tool
    shift
    for tool in "$@"; do command -v "$tool" >/dev/null 2>&1 || { emit unknown "$id"; return 1; }; done
}
number() { [[ $1 =~ ^(0|[1-9][0-9]{0,14})$ ]]; }
# Only the fixed sudo command passes this marker. SUDO_UID is generated by sudo,
# not a caller-provided trust variable. This allowance is for data reads only.
INSPECT_OWNER_UID=$EUID
if [[ $# == 1 && $1 == infrakit-inspect-sudo && $EUID == 0 && ${SUDO_UID:-} =~ ^(0|[1-9][0-9]{0,9})$ ]] && (( SUDO_UID <= 4294967294 )); then
    INSPECT_OWNER_UID=$SUDO_UID
fi
# The CLI embeds the shared library before these probes.
private_file() { infra_private "$1" "${2:-$INSPECT_OWNER_UID}" >/dev/null 2>&1; }
owned_file() { private_file "$1" "$2" && [[ $(stat -c %u -- "$1" 2>/dev/null) == "$2" ]]; }
size_bytes() {
    awk -v value="$1" -v radix="${2:-1024}" 'BEGIN {
        if (value !~ /^[0-9]+([.][0-9]+)?([kKMGTPE]i?B?|B)?$/) exit 1;
        unit=value; sub(/^[0-9.]+/, "", unit);
        amount=value; sub(/[A-Za-z]+$/, "", amount);
        scale=1;
        if (unit ~ /^[kK]/) scale=radix;
        if (unit ~ /^M/) scale=radix^2;
        if (unit ~ /^G/) scale=radix^3;
        if (unit ~ /^T/) scale=radix^4;
        if (unit ~ /^P/) scale=radix^5;
        if (unit ~ /^E/) exit 1;
        printf "%.0f\n", amount*scale;
    }'
}
probe_clock() {
    has "$1" date || return
    NOW=$(date +%s 2>/dev/null)
    if number "$NOW"; then emit pass "$1"; else NOW=; emit unknown "$1"; fi
}
probe_reboot() {
    local output
    has "$1" find || return
    output=$(find /run -maxdepth 1 -name reboot-required -print 2>/dev/null) || { emit unknown "$1"; return; }
    if [[ -n $output ]]; then emit finding "$1"; else emit pass "$1"; fi
}
probe_disk() {
    local id=$1 path=$2 max_used=$3 max_inode=$4 min_free=$5 row used free inode
    has "$id" df awk || return
    row=$(df --output=pcent,avail -k -- "$path" 2>/dev/null) || { emit unknown "$id"; return; }
    row=$(awk 'NR==2 {print $1, $2}' <<< "$row")
    read -r used free <<< "$row"; used=${used%\%}
    row=$(df --output=ipcent -- "$path" 2>/dev/null) || { emit unknown "$id"; return; }
    inode=$(awk 'NR==2 {print $1}' <<< "$row"); inode=${inode%\%}
    number "$used" && number "$free" && number "$inode" || { emit unknown "$id"; return; }
    free=$((free * 1024))
    if (( used >= max_used || inode >= max_inode || free < min_free )); then emit finding "$id" "$used,$inode,$free"; else emit pass "$id" "$used,$inode,$free"; fi
}
probe_journal() {
    local id=$1 max=$2 output bytes
    has "$id" journalctl awk || return
    output=$(journalctl --disk-usage 2>/dev/null) || { emit unknown "$id"; return; }
    [[ $output == 'Archived and active journals take up '*' in the file system.' ]] || { emit unknown "$id"; return; }
    output=${output#*take up }; output=${output% in the file system.}
    bytes=$(size_bytes "$output") && number "$bytes" || { emit unknown "$id"; return; }
    if (( bytes > max )); then emit finding "$id" "$bytes"; else emit pass "$id" "$bytes"; fi
}
ip_address() {
    local address=$1 part head tail compressed=0
    local -a groups
    if [[ $address != *:* ]]; then
        [[ $address =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || return 1
        IFS=. read -r -a groups <<< "$address"
        for part in "${groups[@]}"; do
            [[ $part =~ ^(0|[1-9][0-9]{0,2})$ ]] && (( part <= 255 )) || return 1
        done
        return 0
    fi
    if [[ $address == *.* ]]; then
        ip_address "${address##*:}" || return 1
        address=${address%:*}:0:0
    fi
    [[ $address =~ ^[0-9a-fA-F:]{2,39}$ && $address != *:::* ]] || return 1
    if [[ $address == *::* ]]; then
        compressed=1; head=${address%%::*}; tail=${address#*::}
        [[ $tail != *::* && $head != :* && $head != *: && $tail != :* && $tail != *: ]] || return 1
        address=$head${head:+:}$tail
    else
        [[ $address != :* && $address != *: ]] || return 1
    fi
    IFS=: read -r -a groups <<< "$address"
    for part in "${groups[@]}"; do [[ $part =~ ^[0-9a-fA-F]{1,4}$ ]] || return 1; done
    if (( compressed )); then (( ${#groups[@]} < 8 )); else (( ${#groups[@]} == 8 )); fi
}
probe_sshd() {
    local id=$1 context=$2 root_context=$3 expected=$4 output root_output password keyboard root client_address client_port local_address local_port
    has "$id" sshd awk || return
    # Match LocalAddress/LocalPort must use the actual server endpoint, not a guessed manifest value.
    [[ ${SSH_CONNECTION:-} =~ ^([^[:space:]]+)\ ([1-9][0-9]{0,4})\ ([^[:space:]]+)\ ([1-9][0-9]{0,4})$ ]] || { emit unknown "$id"; return; }
    client_address=${BASH_REMATCH[1]}; client_port=${BASH_REMATCH[2]}; local_address=${BASH_REMATCH[3]}; local_port=${BASH_REMATCH[4]}
    ip_address "$client_address" && ip_address "$local_address" && (( client_port <= 65535 && local_port <= 65535 )) || { emit unknown "$id"; return; }
    context+=",laddr=$local_address,lport=$local_port"; root_context+=",laddr=$local_address,lport=$local_port"
    output=$(sshd -T -C "$context" 2>/dev/null) && root_output=$(sshd -T -C "$root_context" 2>/dev/null) || { emit unknown "$id"; return; }
    password=$(awk '$1=="passwordauthentication" {print $2}' <<< "$output")
    keyboard=$(awk '$1=="kbdinteractiveauthentication" {print $2}' <<< "$output")
    root=$(awk '$1=="permitrootlogin" {print $2}' <<< "$root_output")
    [[ $password =~ ^(yes|no)$ && $keyboard =~ ^(yes|no)$ && $root =~ ^(yes|no|prohibit-password|without-password|forced-commands-only)$ ]] || { emit unknown "$id"; return; }
    [[ $root != without-password ]] || root=prohibit-password
    if [[ $password == no && $keyboard == no && ( $root == no || $root == "$expected" ) ]]; then emit pass "$id"; else emit finding "$id"; fi
}
probe_upgrades() {
    local id=$1 service timer active settings update upgrade enable load
    has "$id" systemctl apt-config awk || return
    load=$(systemctl show unattended-upgrades.service -p LoadState --value 2>/dev/null) || { emit unknown "$id"; return; }
    [[ $load == loaded ]] || { emit finding "$id"; return; }
    load=$(systemctl show apt-daily-upgrade.timer -p LoadState --value 2>/dev/null) || { emit unknown "$id"; return; }
    [[ $load == loaded ]] || { emit finding "$id"; return; }
    service=$(systemctl is-enabled unattended-upgrades.service 2>/dev/null) || { emit finding "$id"; return; }
    timer=$(systemctl is-enabled apt-daily-upgrade.timer 2>/dev/null) || { emit finding "$id"; return; }
    active=$(systemctl is-active apt-daily-upgrade.timer 2>/dev/null) || { emit finding "$id"; return; }
    settings=$(apt-config dump 2>/dev/null) || { emit unknown "$id"; return; }
    enable=$(awk '$1=="APT::Periodic::Enable" {print $2}' <<< "$settings")
    update=$(awk '$1=="APT::Periodic::Update-Package-Lists" {print $2}' <<< "$settings")
    upgrade=$(awk '$1=="APT::Periodic::Unattended-Upgrade" {print $2}' <<< "$settings")
    if [[ $service == enabled && $timer == enabled && $active == active && ( -z $enable || $enable == '"1";' ) && $update == '"1";' && $upgrade == '"1";' ]]; then emit pass "$id"; else emit finding "$id"; fi
}
probe_docker_inventory() {
    local id=$1 expected=$2 output container count=0 expected_count=0
    has "$id" docker || return
    output=$(docker ps --format '{{.Names}}' 2>/dev/null) || { emit unknown "$id"; return; }
    while IFS= read -r container; do
        [[ -n $container ]] || continue
        [[ $container =~ ^[A-Za-z0-9_][A-Za-z0-9_.-]{0,62}$ ]] || { emit unknown "$id"; return; }
        [[ " $expected " == *" $container "* ]] || { emit finding "$id"; return; }
        count=$((count + 1))
    done <<< "$output"
    for container in $expected; do expected_count=$((expected_count + 1)); done
    if (( count != expected_count )); then emit finding "$id"; else emit pass "$id"; fi
}
probe_docker() {
    local id=$1 container=$2 max_bytes=$3 max_files=$4 output running driver size files bytes
    has "$id" docker awk || return
    output=$(docker inspect --format '{{.State.Running}}|{{.HostConfig.LogConfig.Type}}|{{index .HostConfig.LogConfig.Config "max-size"}}|{{index .HostConfig.LogConfig.Config "max-file"}}' "$container" 2>/dev/null) || { emit unknown "$id"; return; }
    IFS='|' read -r running driver size files <<< "$output"
    [[ $running == true ]] || { emit finding "$id"; return; }
    [[ $driver == json-file || $driver == local ]] || { emit unknown "$id"; return; }
    if [[ -z $size || $size == '<no value>' || -z $files || $files == '<no value>' ]]; then emit finding "$id"; return; fi
    # Docker sizes use binary units, including lowercase m/g.
    size=${size/m/M}; size=${size/g/G}
    bytes=$(size_bytes "$size") && number "$bytes" && number "$files" || { emit unknown "$id"; return; }
    if (( bytes == 0 || bytes > max_bytes || files == 0 || files > max_files )); then emit finding "$id" "$bytes,$files"; else emit pass "$id" "$bytes,$files"; fi
}
probe_docker_space() {
    local id=$1 max=$2 output line bytes total=0 count=0
    has "$id" docker awk || return
    output=$(docker system df --format '{{.Reclaimable}}' 2>/dev/null) || { emit unknown "$id"; return; }
    while IFS= read -r line; do
        bytes=$(size_bytes "${line%% *}" 1000) && number "$bytes" || { emit unknown "$id"; return; }
        total=$((total + bytes)); count=$((count + 1))
    done <<< "$output"
    (( count > 0 )) || { emit unknown "$id"; return; }
    if (( total > max )); then emit finding "$id" "$total"; else emit pass "$id" "$total"; fi
}
probe_pm2() {
    local id=$1 unit=$2 pidfile=$3 minimum=$4 expected=$5 pid group cgroups output ordering timeout cmdline load active key value
    has "$id" stat systemctl cat tr awk || return
    [[ -f $pidfile && -r $pidfile && ! -L $pidfile ]] || { emit unknown "$id"; return; }
    pid=$(cat -- "$pidfile" 2>/dev/null)
    [[ $pid =~ ^[1-9][0-9]{0,9}$ && -d /proc/$pid ]] || { emit unknown "$id"; return; }
    cmdline=$(tr '\0' ' ' <"/proc/$pid/cmdline" 2>/dev/null) || { emit unknown "$id"; return; }
    [[ $cmdline == *'PM2 '* ]] || { emit unknown "$id"; return; }
    output=$(systemctl show "$unit" -p LoadState -p ActiveState -p ControlGroup -p After -p TimeoutStopUSec 2>/dev/null) || { emit unknown "$id"; return; }
    while IFS='=' read -r key value; do
        case $key in LoadState) load=$value ;; ActiveState) active=$value ;; ControlGroup) group=$value ;; After) ordering=$value ;; TimeoutStopUSec) timeout=$value ;; esac
    done <<< "$output"
    [[ $load == loaded && $active == active && -n $group && -n $ordering && -n $timeout ]] || { emit unknown "$id"; return; }
    cgroups=$(cat "/proc/$pid/cgroup" 2>/dev/null) || { emit unknown "$id"; return; }
    local found=0 dependency controllers _hierarchy
    while IFS=: read -r _hierarchy controllers value; do
        [[ -z $controllers || $controllers == name=systemd || $controllers == *,name=systemd || $controllers == name=systemd,* ]] || continue
        [[ $value == "$group" || $value == "$group/"* ]] && found=1
    done <<< "$cgroups"
    (( found == 1 )) || { emit finding "$id"; return; }
    for dependency in $expected; do [[ " $ordering " == *" $dependency "* ]] || { emit finding "$id"; return; }; done
    # systemd emits durations such as 1min 30s, not numeric microseconds.
    timeout=$(awk -v value="$timeout" 'BEGIN {
        count=split(value, parts, " "); total=0;
        for(i=1;i<=count;i++) {
            if(parts[i] !~ /^[0-9]+([.][0-9]+)?(us|ms|s|min|h|d)$/) exit 1;
            unit=parts[i]; sub(/^[0-9.]+/, "", unit); n=parts[i]+0;
            if(unit=="us") n/=1000000; if(unit=="ms") n/=1000;
            if(unit=="min") n*=60; if(unit=="h") n*=3600; if(unit=="d") n*=86400;
            total+=n;
        } printf "%d\n",int(total);
    }') && number "$timeout" || { emit unknown "$id"; return; }
    if (( timeout < minimum )); then emit finding "$id" "$timeout"; else emit pass "$id" "$timeout"; fi
}
probe_rotation() {
    local id=$1 directory=$2 maximum=$3 file modified count=0 bad=0 status=
    local -a files=()
    has "$id" find stat gzip || return
    [[ -n $NOW && -d $directory && -r $directory ]] || { emit unknown "$id"; return; }
    # Match env discovery: keep NUL basenames and require find's status before a verdict.
    while IFS= read -r -d '' file; do
        if [[ $file == /status/* ]]; then status=${file#/status/}; else files+=("$file"); fi
    done < <(find "$directory" -maxdepth 1 -type f \( -name '*__*.log' -o -name '*__*.log.gz' \) -printf '%f\0' 2>/dev/null; printf '/status/%s\0' "$?")
    [[ $status == 0 ]] || { emit unknown "$id"; return; }
    for file in "${files[@]}"; do
        [[ -n $file && $file != *'/'* ]] || continue
        modified=$(stat -c %Y -- "$directory/$file" 2>/dev/null) && number "$modified" || { emit unknown "$id"; return; }
        (( modified <= NOW )) || { emit finding "$id"; return; }
        (( NOW - modified <= maximum )) || continue
        count=$((count + 1))
        if [[ $file != *.gz ]] || ! gzip -t -- "$directory/$file" 2>/dev/null; then bad=$((bad + 1)); fi
    done
    if (( count == 0 )); then emit unknown "$id"; elif (( bad > 0 )); then emit finding "$id" "$bad,$count"; else emit pass "$id" "$count"; fi
}
probe_env() {
    local id=$1 path=$2 metadata mode parent base file count=0 status=
    has "$id" stat find || return
    metadata=$(stat -c %a -- "$path" 2>/dev/null) || { emit unknown "$id"; return; }
    mode=$metadata
    if [[ ! -f $path || -L $path || $mode != 600 ]]; then emit finding "$id"; return; fi
    parent=${path%/*}; parent=${parent:-/}; base=${path##*/}
    # NUL preserves newlines in basenames. The slash sentinel cannot be a basename.
    # Read the whole stream and find's status before claiming pass or finding. No scratch files.
    while IFS= read -r -d '' file; do
        if [[ $file == /status/* ]]; then status=${file#/status/}
        elif [[ $file == "$base".bak* || $file == "$base".*.bak* || $file == "$base".backup* ]]; then count=$((count + 1)); fi
    done < <(find "$parent" -maxdepth 1 \( -type f -o -type l \) -printf '%f\0' 2>/dev/null; printf '/status/%s\0' "$?")
    [[ $status == 0 ]] || { emit unknown "$id"; return; }
    if (( count > 0 )); then emit finding "$id" "$count"; else emit pass "$id"; fi
}
probe_backup() {
    local id=$1 directory=$2 maximum=$3 job=$4 archive=$5 remote=$6 uid=$7 snapshot receipt age marker hash filename count=0 complete=0 manifest=0
    local -a INFRA_PROOF=() owner=() files=()
    has "$id" stat cat cmp sort || return
    [[ -n $NOW ]] || { emit unknown "$id"; return; }
    owned_file "$directory/last-success" "$uid" && owned_file "$directory/.infrakit-owner" "$uid" &&
        owned_file "$archive/.infrakit-owner" "$uid" && owned_file "$directory/offsite-enabled" "$uid" || { emit unknown "$id"; return; }
    infra_read_proof "$directory/last-success" "$uid" >/dev/null 2>&1 || { emit finding "$id"; return; }
    mapfile -t owner 2>/dev/null <"$directory/.infrakit-owner" || { emit unknown "$id"; return; }
    [[ ${INFRA_PROOF[1]} == "$job" && ${INFRA_PROOF[4]} == "$remote" &&
        ${#owner[@]} == 4 && ${owner[0]} == infrakit-owner-v1 && ${owner[1]} == "$job" &&
        ${owner[2]} == "$archive" && ${owner[3]} == "$remote" ]] || { emit finding "$id"; return; }
    cmp -s "$directory/.infrakit-owner" "$archive/.infrakit-owner" || { emit finding "$id"; return; }
    snapshot=${INFRA_PROOF[2]}; receipt="$directory/receipts/$snapshot"
    owned_file "$receipt/proof" "$uid" && owned_file "$receipt/files" "$uid" && owned_file "$receipt/complete.sha256" "$uid" || { emit unknown "$id"; return; }
    cmp -s "$directory/last-success" "$receipt/proof" && sort -cu "$receipt/files" 2>/dev/null || { emit finding "$id"; return; }
    hash=$(cat "$receipt/complete.sha256" 2>/dev/null) && [[ $hash =~ ^[0-9a-f]{64}$ ]] || { emit finding "$id"; return; }
    mapfile -t files 2>/dev/null <"$receipt/files" || { emit unknown "$id"; return; }
    for filename in "${files[@]}"; do
        [[ $filename =~ ^[A-Za-z0-9_.-]+\.age$ && $filename != *..* ]] || { emit finding "$id"; return; }
        count=$((count + 1))
        [[ $filename != complete.age ]] || complete=1
        [[ $filename != manifest.txt.age ]] || manifest=1
    done
    (( count >= 3 && complete && manifest )) || { emit finding "$id"; return; }
    marker=$(cat "$directory/offsite-enabled" 2>/dev/null) || { emit unknown "$id"; return; }
    [[ $marker == "$remote/$snapshot" ]] || { emit finding "$id"; return; }
    age=$((NOW - INFRA_PROOF[3]))
    if (( age < 0 || age > maximum )); then emit finding "$id" "$age"; else emit pass "$id" "$age"; fi
}
probe_certificate() {
    local id=$1 path=$2 container=$3 minimum=$4 output expires days
    has "$id" openssl date || return
    [[ -n $NOW ]] || { emit unknown "$id"; return; }
    if [[ -n $container ]]; then
        has "$id" docker || return
        output=$(docker exec "$container" cat -- "$path" 2>/dev/null | openssl x509 -noout -enddate 2>/dev/null) || { emit unknown "$id"; return; }
    else
        output=$(openssl x509 -in "$path" -noout -enddate 2>/dev/null) || { emit unknown "$id"; return; }
    fi
    [[ $output == notAfter=* ]] || { emit unknown "$id"; return; }
    expires=$(date -d "${output#notAfter=}" +%s 2>/dev/null) && number "$expires" || { emit unknown "$id"; return; }
    days=$(((expires - NOW) / 86400))
    if (( expires - NOW < minimum * 86400 )); then emit finding "$id" "$days"; else emit pass "$id" "$days"; fi
}
probe_redis() {
    local id=$1 port=$2 auth=$3 maximum=$4 password output used cap percent
    has "$id" redis-cli awk stat cat || return
    if [[ -n $auth ]]; then
        private_file "$auth" || { emit unknown "$id"; return; }
        password=$(cat -- "$auth" 2>/dev/null) || { emit unknown "$id"; return; }
        [[ -n $password && $password != *$'\n'* && $password != *$'\r'* ]] || { emit unknown "$id"; return; }
        output=$(REDISCLI_AUTH="$password" redis-cli --no-auth-warning -h 127.0.0.1 -p "$port" --raw INFO memory 2>/dev/null) || { emit unknown "$id"; return; }
        unset password
    else
        output=$(redis-cli --no-auth-warning -h 127.0.0.1 -p "$port" --raw INFO memory 2>/dev/null) || { emit unknown "$id"; return; }
    fi
    used=$(awk -F: '$1=="used_memory" {gsub(/\r/, "", $2); print $2}' <<< "$output")
    cap=$(awk -F: '$1=="maxmemory" {gsub(/\r/, "", $2); print $2}' <<< "$output")
    number "$used" && number "$cap" || { emit unknown "$id"; return; }
    (( cap > 0 )) || { emit finding "$id" "$used,0"; return; }
    percent=$((used * 100 / cap))
    if (( used * 100 >= cap * maximum )); then emit finding "$id" "$used,$cap,$percent"; else emit pass "$id" "$used,$cap,$percent"; fi
}
probe_mail_config() {
    local id=$1 path=$2 fields
    has "$id" stat awk || return
    private_file "$path" || { emit unknown "$id"; return; }
    # These are field-presence checks, not Bash evaluation or a delivery claim.
    fields=$(awk '
        /^[[:space:]]*SMTP_(HOST|USER|PASS|FROM|TO)=/ {
            key=$0; sub(/=.*/, "", key); sub(/^[[:space:]]*/, "", key);
            value=$0; sub(/^[^=]*=/, "", value);
            sub(/^[[:space:]]*/, "", value); sub(/[[:space:]]+#.*/, "", value); sub(/[[:space:]]*$/, "", value);
            # Refuse known empty values without running this trusted Bash file.
            quote=sprintf("%c",39);
            if (value=="" || value=="\"\"" || value==quote quote || value ~ /^\([[:space:]]*\)$/ || value ~ /^#/) delete seen[key];
            else seen[key]=1;
        }
        END { for (key in seen) count++; print count+0 }
    ' "$path" 2>/dev/null) || { emit unknown "$id"; return; }
    if [[ $fields == 5 ]]; then emit pass "$id"; else emit finding "$id"; fi
}
probe_mail_test() {
    local id=$1 path=$2 config=$3 maximum=$4 changed age
    local -a proof
    has "$id" stat || return
    [[ -n $NOW ]] && private_file "$path" && private_file "$config" || { emit unknown "$id"; return; }
    mapfile -t proof <"$path"
    [[ ${#proof[@]} == 3 && ${proof[0]} == infrakit-mail-test-v1 && ${proof[2]} == recipient-confirmed ]] && number "${proof[1]}" || { emit finding "$id"; return; }
    changed=$(stat -c %Y -- "$config" 2>/dev/null) && number "$changed" || { emit unknown "$id"; return; }
    age=$((NOW - proof[1]))
    if (( age < 0 || age > maximum || changed > proof[1] )); then emit finding "$id" "$age"; else emit pass "$id" "$age"; fi
}
